#!/usr/bin/env python3
"""Regenerate the F9/F8 Han glyph pages from the OFL BDF subset (stdlib only)."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / 'graphics/fonts/chinese'
BEGIN = '@ BEGIN GENERATED CHINESE FONT'
END = '@ END GENERATED CHINESE FONT'
# F9 20..CF sits between the stock arrows (F9 00..1A) and emoji (F9 D0..FE).
PAGE1_FIRST = 0x20
PAGE1_LIMIT = 0xD0
PAGE1_CAP = PAGE1_LIMIT - PAGE1_FIRST
# F8 00..0C are keypad icons. Stop before F7 so a trail byte is not a control.
PAGE2_FIRST = 0x20
PAGE2_LIMIT = 0xF7
PAGE2_CAP = PAGE2_LIMIT - PAGE2_FIRST


def output(path, text):
    if "--check" in sys.argv:
        assert path.read_text() == text, f"Stale generated file: {path}"
    else:
        path.write_text(text)


def encode(index):
    if index < PAGE1_CAP:
        return f'F9 {PAGE1_FIRST + index:02X}'
    index -= PAGE1_CAP
    assert index < PAGE2_CAP, 'Han manifest exceeds the safe F9/F8 suffix range'
    return f'F8 {PAGE2_FIRST + index:02X}'


def generate():
    chars = (ASSETS / 'characters.txt').read_text().strip()
    assert len(chars) == len(set(chars)) and len(chars) <= PAGE1_CAP + PAGE2_CAP
    glyphs = {}
    for block in (ASSETS / 'opening-12.bdf').read_text().split('STARTCHAR ')[1:]:
        code = int(re.search(r'^ENCODING (\d+)$', block, re.M)[1])
        w, h, xoff, yoff = map(int, re.search(r'^BBX (.*)$', block, re.M)[1].split())
        rows = block.split('BITMAP\n')[1].split('ENDCHAR')[0].split()
        pixels = [[0] * 16 for _ in range(16)]
        for y, row in enumerate(rows):
            for x in range(w):
                if int(row, 16) & (1 << ((w + 7) // 8 * 8 - 1 - x)):
                    px, py = x + xoff, 10 - h - yoff + y
                    assert 0 <= px < 12 and 0 <= py < 12, f'U+{code:04X} pixel outside 12x12'
                    pixels[py][px] = 1
        assert any(map(any, pixels)), f'Blank glyph U+{code:04X}'
        # Four 8x8 tiles: TL, TR, BL, BR. Two bits/pixel, leftmost in bits 14..15.
        glyphs[chr(code)] = [sum(pixels[ty+y][tx+x] << (14-2*x) for x in range(8))
                            for ty, tx in ((0, 0), (0, 8), (8, 0), (8, 8)) for y in range(8)]
    missing = [c for c in chars if c not in glyphs]
    assert not missing, 'BDF is missing ' + ' '.join(f'U+{ord(c):04X}' for c in missing)
    page1 = min(len(chars), PAGE1_CAP)
    page2 = len(chars) - page1
    header = ['// Generated by tools/chinese_font/generate.py. Font license: graphics/fonts/chinese/OFL.txt.',
              '#define CHINESE_GLYPH_FIRST 0x120',
              f'#define CHINESE_PAGE1_COUNT {page1}',
              '#define CHINESE_PAGE2_GLYPH_FIRST 0x220',
              '#define CHINESE_PAGE2_SUFFIX_FIRST 0x20',
              f'#define CHINESE_PAGE2_COUNT {page2}',
              f'#define CHINESE_GLYPH_COUNT {len(chars)}',
              '#define CHINESE_GLYPH_WIDTH 12',
              'static const u16 sChineseGlyphs[CHINESE_GLYPH_COUNT][32] = {']
    for char in chars:
        header.append(f'    // {char} U+{ord(char):04X}')
        header.append('    {' + ', '.join(f'0x{v:04X}' for v in glyphs[char]) + '},')
    header.append('};\n')
    (ROOT / 'src/data/fonts').mkdir(exist_ok=True)
    output(ROOT / 'src/data/fonts/chinese.h', '\n'.join(header))
    path = ROOT / 'charmap.txt'
    text = path.read_text()
    block = BEGIN + '\n' + ''.join(f"'{c}' = {encode(i)}\n" for i, c in enumerate(chars)) + END
    if BEGIN in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END)+len(END):]
    else:
        text += '\n' + block + '\n'
    output(path, text)


if __name__ == '__main__':
    generate()
